#!/usr/bin/env python3
"""Train and visualize a neural network predicting double-pendulum motion.

The model learns one-step dynamics from states generated by a Runge–Kutta
simulator. Angles are represented by sine/cosine pairs to avoid the -pi/pi
discontinuity. Example:

    pip install numpy torch matplotlib
    python train_double_pendulum.py --epochs 40 --trajectories 300
    python train_double_pendulum.py --evaluate --eval-trajectories 30
    python train_double_pendulum.py --predict 5.0 0.2 0.0 0.0 0.0

Prediction arguments are duration (seconds), then initial theta1, theta2,
omega1, omega2 (angles in radians). Requires numpy and PyTorch.
"""

import argparse
import copy
import math
from pathlib import Path

import numpy as np
import torch
from torch import nn


DT = 0.02
G = 9.81
M1 = M2 = L1 = L2 = 1.0
OMEGA_SCALE = 10.0


def derivative(state):
    """Return [theta1', theta2', omega1', omega2'] for equal unit masses."""
    t1, t2, w1, w2 = state
    delta = t1 - t2
    den = 2 * M1 + M2 - M2 * math.cos(2 * delta)
    a1 = (
        -G * (2 * M1 + M2) * math.sin(t1)
        - M2 * G * math.sin(t1 - 2 * t2)
        - 2 * math.sin(delta) * M2 * (w2 * w2 * L2 + w1 * w1 * L1 * math.cos(delta))
    ) / (L1 * den)
    a2 = (
        2 * math.sin(delta)
        * (w1 * w1 * L1 * (M1 + M2) + G * (M1 + M2) * math.cos(t1)
           + w2 * w2 * L2 * M2 * math.cos(delta))
    ) / (L2 * den)
    return np.array([w1, w2, a1, a2], dtype=np.float64)


def rk4_step(state, dt=DT):
    k1 = derivative(state)
    k2 = derivative(state + dt * k1 / 2)
    k3 = derivative(state + dt * k2 / 2)
    k4 = derivative(state + dt * k3)
    result = state + dt * (k1 + 2 * k2 + 2 * k3 + k4) / 6
    # Keep angles bounded for numerical stability during long simulations.
    result[:2] = (result[:2] + np.pi) % (2 * np.pi) - np.pi
    return result


def encode(state):
    t1, t2, w1, w2 = state.T
    return np.column_stack((np.sin(t1), np.cos(t1), np.sin(t2), np.cos(t2),
                            w1 / OMEGA_SCALE, w2 / OMEGA_SCALE))


def make_data(trajectories, steps, seed):
    rng = np.random.default_rng(seed)
    inputs, targets, trajectory_ids, raw_trajectories = [], [], [], []
    for trajectory_id in range(trajectories):
        state = np.array([rng.uniform(-np.pi, np.pi), rng.uniform(-np.pi, np.pi),
                          rng.uniform(-2, 2), rng.uniform(-2, 2)], dtype=np.float64)
        states = []
        for _ in range(steps + 1):
            states.append(state.copy())
            state = rk4_step(state)
            if not np.isfinite(state).all() or np.max(np.abs(state[2:])) > 1e4:
                break
        states = np.asarray(states)
        raw_trajectories.append(states)
        if len(states) > 1:
            inputs.append(encode(states[:-1]))
            targets.append(encode(states[1:]))
            trajectory_ids.append(np.full(len(states) - 1, trajectory_id, dtype=np.int32))
    return (np.concatenate(inputs).astype(np.float32),
            np.concatenate(targets).astype(np.float32),
            np.concatenate(trajectory_ids), raw_trajectories)


class DynamicsModel(nn.Module):
    def __init__(self, width=128):
        super().__init__()
        self.layers = nn.Sequential(
            nn.Linear(6, width), nn.Tanh(),
            nn.Linear(width, width), nn.Tanh(),
            nn.Linear(width, width), nn.Tanh(),
            nn.Linear(width, 6),
        )

    def forward(self, x):
        return self.layers(x)


def normalize_encoded_torch(encoded):
    """Keep predicted angle sine/cosine pairs on the unit circle."""
    angle1 = torch.nn.functional.normalize(encoded[..., 0:2], dim=-1, eps=1e-8)
    angle2 = torch.nn.functional.normalize(encoded[..., 2:4], dim=-1, eps=1e-8)
    return torch.cat((angle1, angle2, encoded[..., 4:6]), dim=-1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--epochs", type=int, default=30)
    parser.add_argument("--trajectories", type=int, default=200)
    parser.add_argument("--steps", type=int, default=500, help="steps per generated trajectory")
    parser.add_argument("--batch-size", type=int, default=1024)
    parser.add_argument("--epoch-delay", type=float, default=0.0,
                        help="seconds to pause after each epoch's prediction animation")
    parser.add_argument("--batches-per-epoch", type=int, default=80,
                        help="training batches per epoch; lower values make chart updates arrive sooner")
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--output", type=Path, default=Path("double_pendulum.pt"))
    parser.add_argument("--no-plot", action="store_true", help="disable the live matplotlib training window")
    parser.add_argument("--evaluate", action="store_true", help="measure saved-model accuracy on fresh trajectories")
    parser.add_argument("--long-term", action="store_true",
                        help="run long-horizon evaluation (default: 30 seconds on unseen trajectories)")
    parser.add_argument("--eval-trajectories", type=int, default=20, help="number of unseen test trajectories")
    parser.add_argument("--eval-seconds", type=float, default=None, help="duration of each evaluation rollout")
    parser.add_argument("--predict", nargs=5, type=float, metavar=("SECONDS", "THETA1", "THETA2", "OMEGA1", "OMEGA2"))
    args = parser.parse_args()
    if args.long_term:
        args.evaluate = True
    if args.eval_seconds is None:
        args.eval_seconds = 30.0 if args.long_term else 5.0
    torch.manual_seed(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

    if args.evaluate:
        if args.eval_trajectories < 1 or args.eval_seconds <= 0:
            parser.error("eval-trajectories and eval-seconds must be positive")
        if not args.output.exists():
            parser.error(f"Model checkpoint not found: {args.output}. Train a model first.")
        checkpoint = torch.load(args.output, map_location=device, weights_only=True)
        if checkpoint.get("omega_scale") != OMEGA_SCALE:
            parser.error("This checkpoint uses the old input scale. Retrain the model before evaluating it.")
        model = DynamicsModel(checkpoint["width"]).to(device)
        model.load_state_dict(checkpoint["model"])
        model.eval()
        n_steps = max(1, round(args.eval_seconds / DT))
        rng = np.random.default_rng(args.seed + 1_000_003)
        all_angle_errors, all_velocity_errors = [], []
        first_true = first_pred = None
        divergence_times = []
        with torch.no_grad():
            for trajectory in range(args.eval_trajectories):
                initial = np.array([rng.uniform(-np.pi, np.pi), rng.uniform(-np.pi, np.pi),
                                    rng.uniform(-2, 2), rng.uniform(-2, 2)])
                true_states = [initial.copy()]
                for _ in range(n_steps):
                    true_states.append(rk4_step(true_states[-1]))
                initial_encoded = torch.from_numpy(encode(initial[None]).astype(np.float32)).to(device)
                encoded_states = [initial_encoded]
                state_encoded = initial_encoded
                failed_at = None
                for step in range(n_steps):
                    state_encoded = normalize_encoded_torch(model(state_encoded))
                    if not torch.isfinite(state_encoded).all():
                        failed_at = step + 1
                        break
                    encoded_states.append(state_encoded)
                predicted_encoded = torch.cat(encoded_states, dim=0).cpu().numpy()
                if failed_at is not None:
                    predicted_encoded = np.concatenate((predicted_encoded,
                        np.full((n_steps + 1 - len(predicted_encoded), 6), np.nan, dtype=np.float32)))
                    divergence_times.append(failed_at * DT)
                pred_states = np.column_stack((
                    np.arctan2(predicted_encoded[:, 0], predicted_encoded[:, 1]),
                    np.arctan2(predicted_encoded[:, 2], predicted_encoded[:, 3]),
                    predicted_encoded[:, 4] * OMEGA_SCALE,
                    predicted_encoded[:, 5] * OMEGA_SCALE,
                ))
                true_states, pred_states = np.asarray(true_states), np.asarray(pred_states)
                # Circular difference keeps angle errors correct across the +/-pi seam.
                angle_error = np.arctan2(np.sin(pred_states[:, :2] - true_states[:, :2]),
                                         np.cos(pred_states[:, :2] - true_states[:, :2]))
                velocity_error = pred_states[:, 2:] - true_states[:, 2:]
                all_angle_errors.append(angle_error)
                all_velocity_errors.append(velocity_error)
                if trajectory == 0:
                    first_true, first_pred = true_states, pred_states

        angle_errors = np.stack(all_angle_errors)
        velocity_errors = np.stack(all_velocity_errors)
        point_error = np.sqrt(np.nanmean(angle_errors ** 2, axis=2))
        per_time_angle_rmse = np.sqrt(np.nanmean(angle_errors ** 2, axis=(0, 2)))
        per_time_velocity_rmse = np.sqrt(np.nanmean(velocity_errors ** 2, axis=(0, 2)))
        print(f"Long-horizon evaluation: {args.eval_trajectories} unseen starts, {n_steps * DT:.2f}s per rollout")
        print("Angle errors use wrapped (circular) differences. Time-to-threshold is first time per run that two-angle RMS exceeds 0.5 rad.")
        print(f"Overall angle RMSE:    {np.sqrt(np.nanmean(angle_errors ** 2)):.6f} rad")
        print(f"Overall velocity RMSE: {np.sqrt(np.nanmean(velocity_errors ** 2)):.6f} rad/s")
        thresholds = []
        for run_error in point_error:
            crossed = np.flatnonzero(run_error > 0.5)
            if len(crossed):
                thresholds.append(crossed[0] * DT)
        if thresholds:
            print(f"Median time to 0.5-rad error: {np.median(thresholds):.2f}s ({len(thresholds)}/{args.eval_trajectories} runs crossed)")
        else:
            print("No trajectory crossed 0.5 rad during this test window.")
        if divergence_times:
            print(f"Non-finite AI rollout: {len(divergence_times)}/{args.eval_trajectories} runs; median failure at {np.median(divergence_times):.2f}s")
        report_times = sorted(set(t for t in (0.2, 1.0, 2.0, 5.0, 10.0, 20.0, 30.0, args.eval_seconds) if t <= args.eval_seconds))
        for seconds in report_times:
            index = min(n_steps, max(1, round(seconds / DT)))
            print(f"At {index * DT:5.2f}s: angle RMSE={per_time_angle_rmse[index]:.6f} rad, "
                  f"velocity RMSE={per_time_velocity_rmse[index]:.6f} rad/s")
        if not args.no_plot:
            try:
                import matplotlib.pyplot as plt
            except ImportError:
                parser.error("Evaluation plots require matplotlib. Install it with: pip install matplotlib")
            t = np.arange(n_steps + 1) * DT
            fig, axes = plt.subplots(2, 1, figsize=(11, 8), sharex=True)
            axes[0].plot(t, first_true[:, 0], label="Simulator θ₁", linewidth=1.8)
            axes[0].plot(t, first_pred[:, 0], "--", label="AI θ₁", linewidth=1.5)
            axes[0].set_ylabel("Angle θ₁ (rad)")
            axes[0].grid(True, alpha=0.3)
            axes[0].legend()
            times = np.arange(n_steps + 1) * DT
            median = np.nanmedian(point_error, axis=0)
            lower, upper = np.nanpercentile(point_error, (10, 90), axis=0)
            axes[1].plot(times, median, color="#b33b2e", label="Median two-angle error")
            axes[1].fill_between(times, lower, upper, color="#e9a29a", alpha=0.35, label="10th–90th percentile")
            axes[1].axhline(0.5, color="#444", linestyle=":", label="0.5 rad tolerance")
            axes[1].set(xlabel="Time (s)", ylabel="Angle error (rad)")
            axes[1].grid(True, alpha=0.3)
            axes[1].legend()
            fig.suptitle("Unseen long-term rollouts: AI vs simulator")
            fig.tight_layout()
            plt.show()
        return

    if args.predict:
        checkpoint = torch.load(args.output, map_location=device, weights_only=True)
        if checkpoint.get("omega_scale") != OMEGA_SCALE:
            parser.error("This checkpoint uses the old input scale. Retrain the model before predicting.")
        model = DynamicsModel(checkpoint["width"]).to(device)
        model.load_state_dict(checkpoint["model"])
        model.eval()
        duration, *initial = args.predict
        state = np.asarray(initial, dtype=np.float64)
        history = [state.copy()]
        with torch.no_grad():
            for _ in range(max(0, round(duration / DT))):
                x = torch.from_numpy(encode(state[None]).astype(np.float32)).to(device)
                y = model(x).cpu().numpy()[0]
                # Normalize each predicted sine/cosine pair back onto the circle.
                for i in (0, 2):
                    norm = max(np.hypot(y[i], y[i + 1]), 1e-8)
                    y[i:i + 2] /= norm
                state = np.array([math.atan2(y[0], y[1]), math.atan2(y[2], y[3]),
                                  y[4] * OMEGA_SCALE, y[5] * OMEGA_SCALE])
                history.append(state.copy())
        print("time_s,theta1_rad,theta2_rad,omega1_rad_s,omega2_rad_s")
        for i, row in enumerate(history):
            print(f"{i * DT:.3f}," + ",".join(f"{v:.6f}" for v in row))
        return

    if args.epochs < 1 or args.trajectories < 2 or args.steps < 1 or args.batch_size < 1:
        parser.error("epochs, steps, and batch-size must be positive; trajectories must be at least 2")
    if args.batches_per_epoch < 1:
        parser.error("batches-per-epoch must be at least 1")
    if args.epoch_delay < 0:
        parser.error("epoch-delay cannot be negative")
    print(f"Generating {args.trajectories} trajectories ({args.steps} steps each)...")
    x, y, trajectory_ids, raw_trajectories = make_data(args.trajectories, args.steps, args.seed)
    # Hold out complete trajectories so validation measures new initial conditions.
    rng = np.random.default_rng(args.seed)
    trajectory_order = rng.permutation(args.trajectories)
    split = max(1, int(0.9 * len(trajectory_order)))
    train_trajectories = trajectory_order[:split]
    val_trajectories = trajectory_order[split:]
    train_ids = np.flatnonzero(np.isin(trajectory_ids, train_trajectories))
    val_ids = np.flatnonzero(np.isin(trajectory_ids, val_trajectories))
    x_train = torch.from_numpy(x[train_ids]).to(device)
    y_train = torch.from_numpy(y[train_ids]).to(device)
    x_val = torch.from_numpy(x[val_ids]).to(device)
    y_val = torch.from_numpy(y[val_ids]).to(device)
    model = DynamicsModel().to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=1e-3)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="min", factor=0.5, patience=8, min_lr=1e-5
    )
    loss_fn = nn.MSELoss()
    best_val_loss = float("inf")
    best_model_state = None
    if not args.no_plot:
        try:
            import matplotlib.pyplot as plt
        except ImportError:
            parser.error("Live plots require matplotlib. Install it with: pip install matplotlib")
        # Cycle through trajectories whose transitions are included in training.
        plotted_trajectories = [int(i) for i in train_trajectories
                                if len(raw_trajectories[int(i)]) > 1]
        plt.ion()
        fig, (loss_ax, motion_ax) = plt.subplots(1, 2, figsize=(13, 5.5))
        fig.suptitle("DOUBLE PENDULUM  /  LIVE TRAINING", fontsize=15, fontweight="bold")
        fig.patch.set_facecolor("#f4f6fa")
        for ax in (loss_ax, motion_ax):
            ax.set_facecolor("white")
            ax.grid(True, color="#dfe4ec", linewidth=0.8)
            ax.spines["top"].set_visible(False)
            ax.spines["right"].set_visible(False)
        train_line, = loss_ax.plot([], [], color="#3167d5", linewidth=2.5, label="Train")
        val_line, = loss_ax.plot([], [], color="#f28e2b", linewidth=2.5, label="Validation")
        loss_ax.set(title="LEARNING  ·  one-step error", xlabel="Epoch", ylabel="Mean squared error")
        loss_ax.set_yscale("log")
        loss_ax.legend(frameon=False, loc="upper right")
        true_line, = motion_ax.plot([], [], color="#26354a", linewidth=2.4, label="Simulator θ₁")
        pred_line, = motion_ax.plot([], [], color="#ed5a45", linewidth=2.8, label="AI θ₁")
        motion_ax.set(title="TRAINING WINDOW  ·  AI rollout", xlabel="Time (seconds)", ylabel="Angle θ₁ (radians)")
        motion_ax.set_ylim(-np.pi, np.pi)
        motion_ax.legend(frameon=False, loc="upper right")
        fig.subplots_adjust(left=0.07, right=0.98, bottom=0.13, top=0.83, wspace=0.24)
        try:
            fig.canvas.manager.set_window_title("Double pendulum training")
        except AttributeError:
            pass
        train_history, val_history = [], []
    for epoch in range(1, args.epochs + 1):
        model.train()
        total = 0.0
        batches = args.batches_per_epoch
        for _ in range(batches):
            ids = rng.integers(0, len(x_train), size=min(args.batch_size, len(x_train)))
            loss = loss_fn(model(x_train[ids]), y_train[ids])
            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            optimizer.step()
            total += loss.item() * len(ids)
        model.eval()
        with torch.no_grad():
            val_loss = loss_fn(model(x_val), y_val).item()
        scheduler.step(val_loss)
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            best_model_state = copy.deepcopy(model.state_dict())
        train_loss = total / (batches * min(args.batch_size, len(x_train)))
        lr = optimizer.param_groups[0]["lr"]
        print(f"epoch {epoch:03d}/{args.epochs}: train_mse={train_loss:.6g} val_mse={val_loss:.6g} lr={lr:.2g}")
        if not args.no_plot:
            train_history.append(train_loss)
            val_history.append(val_loss)
            train_line.set_data(range(1, epoch + 1), train_history)
            val_line.set_data(range(1, epoch + 1), val_history)
            loss_ax.relim()
            loss_ax.autoscale_view()
            # Show an actual training trajectory and a two-second autoregressive
            # model rollout from the same starting state.
            trajectory_id = plotted_trajectories[(epoch - 1) % len(plotted_trajectories)]
            demo_true = raw_trajectories[trajectory_id]
            demo_steps = min(100, len(demo_true) - 1)
            demo_true = demo_true[:demo_steps + 1]
            time_axis = np.arange(demo_steps + 1) * DT
            demo_start = demo_true[0].copy()
            true_line.set_data(time_axis, demo_true[:, 0])
            motion_ax.set_xlim(0, time_axis[-1])

            predicted_states = [
                torch.from_numpy(encode(demo_start[None]).astype(np.float32)).to(device)
            ]
            state_encoded = predicted_states[0]
            with torch.no_grad():
                for _ in range(demo_steps):
                    state_encoded = normalize_encoded_torch(model(state_encoded))
                    predicted_states.append(state_encoded)
            predicted_encoded = torch.cat(predicted_states, dim=0).cpu().numpy()
            rollout_theta1 = np.arctan2(predicted_encoded[:, 0], predicted_encoded[:, 1])
            motion_ax.set_title(
                f"TRAINING TRAJECTORY #{trajectory_id + 1}  ·  {demo_steps * DT:.2f}s  ·  epoch {epoch}/{args.epochs}"
            )
            fig.canvas.draw_idle()
            plt.pause(0.01)
            # Animate independently of the configurable pause below.
            frame_ends = np.linspace(1, len(rollout_theta1), 6, dtype=int)[1:]
            for end in frame_ends:
                pred_line.set_data(time_axis[:end], rollout_theta1[:end])
                fig.canvas.draw_idle()
                plt.pause(0.001)
            pred_line.set_data(time_axis, rollout_theta1)
            fig.canvas.draw_idle()
            if args.epoch_delay:
                plt.pause(args.epoch_delay)

    if best_model_state is not None:
        model.load_state_dict(best_model_state)
    torch.save({"model": model.cpu().state_dict(), "width": 128, "dt": DT,
                "omega_scale": OMEGA_SCALE,
                "description": "One-step double-pendulum predictor with scaled angular velocities."}, args.output)
    print(f"Saved best validation model (MSE={best_val_loss:.6g}) to {args.output}")
    print(f"To roll out a prediction: python {Path(__file__).name} --output {args.output} --predict 5 0.2 0 0 0")

    if not args.no_plot:
        plt.ioff()
        plt.show()


if __name__ == "__main__":
    main()
